#!/usr/bin/env python3
import json,sys
from pathlib import Path
sys.path.insert(0,str(Path(__file__).resolve().parent)); import generate_variants as g
HERE=Path(__file__).resolve().parent

def apply(base, data, reset_qs=(), retain_qs=(), rx_qs=()):
    text=base
    # Retention deletes only the existing reset line, preserving all source
    # line indices used by the other text transforms.
    if retain_qs:
        lines=text.splitlines(); rs={r[0]:r for r in g.retained_sites(lines)}
        text=g.transform_retain(text,[rs[q] for q in retain_qs])
    if rx_qs:
        lines=text.splitlines(); sites={r[0]:r for r in g.first_rx_sites(lines)}
        # Classifications are already exact-checked on the base circuit. The
        # detector map is source-order invariant under these independent folds.
        for q in rx_qs:
            q0,ri,hi=sites[q]; provisional,b=g.transform_rx(text,(q0,ri,hi),[],'x')
            _,dets=g.random_detectors(provisional,data)
            # The provisional detector list is needed in source order, but the
            # new record must be folded into the exact deterministic parity.
            text='\n'.join(g.add_bit_to_detectors(provisional.splitlines(),b[0],dets))+'\n'
    if reset_qs:
        text,_=g.transform_reset(text,tuple(reset_qs),'combo')
    return text

def main():
  specs=[
    ('v12','work/submissions/v12_L5lns12_r86.qasm','work/submissions/v12_L5lns12_r86.json',[(),(4,),(10,),(19,),(4,10,19)]),
    ('cand14','work/lanes/ST_BC/cand14.qasm','work/lanes/ST_BC/cand14.json',[(),(29,),(4,5,10,11,25,28,29)]),
  ]
  for target,sp,jp,rxs in specs:
    base=Path(sp).read_text(); data=json.loads(Path(jp).read_text())['data_qubits']
    sets=[]
    for r in [(), (16,) if target=='v12' else (23,)]:
      for ret in [(), (8,)]:
       for rx in rxs:
        if not r and not ret and (rx==()): continue
        sets.append((r,ret,rx))
    # Keep the full combinations small and explicit; individual site files are
    # generated by generate_variants.py.
    for r,ret,rx in sets:
      tag='_'.join(['r'+('_'.join(map(str,r)) if r else '0'), 'ret'+('_'.join(map(str,ret)) if ret else '0'), 'rx'+('_'.join(map(str,rx)) if rx else '0')])
      text=apply(base,data,r,ret,rx)
      g.write(f'{target}_combo_{tag}',text,g.report_meta(sp,text,data,'combined',list(r)+list(ret)+list(rx),{'reset':r,'retain':ret,'rx':rx}))

if __name__=='__main__': main()
